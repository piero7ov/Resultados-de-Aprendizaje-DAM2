// Entrada
document.addEventListener("keydown", function(evento) {
  switch (evento.key) {
    case "ArrowUp":
      console.log("UP");
      break;

    case "ArrowDown":
      console.log("DOWN");
      break;

    case "ArrowLeft":
      console.log("LEFT");
      break;

    case "ArrowRight":
      console.log("RIGHT");
      break;
  }
});

document.addEventListener("keyup", function(evento) {
  switch (evento.key) {
    case "ArrowUp":
      console.log("UP");
      break;

    case "ArrowDown":
      console.log("DOWN");
      break;

    case "ArrowLeft":
      console.log("LEFT");
      break;

    case "ArrowRight":
      console.log("RIGHT");
      break;
  }
});
